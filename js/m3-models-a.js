/* tower sits at the back (−Z). Users sit/stand toward +Z. */
function mBase(c, o) {
  o = o || {}; const hz = c.d / 2, tz = o.tz ?? -hz + .2, tx = o.tx || 0, th = o.th || Math.min(c.h, 1.9);
  c.tower(tx, tz, th, { w: o.tw || .56 });
  const fz = hz - .06;
  c.fr([tx, .04, tz + .18], [tx, .04, fz], .08);
  c.fr([-(o.bw || .36), .04, fz], [(o.bw || .36), .04, fz], .08);
  c.foot(-(o.bw || .36), fz); c.foot((o.bw || .36), fz);
  return { tz, th, fz };
}
